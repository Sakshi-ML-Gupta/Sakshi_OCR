"""
pipeline.py — Sakshi OCR: IGNOU Assignment Q&A Extraction Pipeline

Stages:
  1. OCR (Datalab Chandra, mode=accurate, paginate=true)
  2. Raw text -> numbered lines
  3. Question extraction (LLM returns question text is allowed here — this stage
     is NOT under the raw-only constraint, only ANSWER mapping is)
  4. Sequential answer mapping (map_answers_with_llm_sequential)
       - chunked calls to Claude using the strict line-range-mapper system prompt
       - answers are NEVER generated by the LLM — only line numbers are returned
       - code slices the raw OCR text using those line numbers
  5. Self-correction / validation loop (see module docstring below)
  6. Rescue passes for unmatched questions
  7. Final assembly

HARD CONSTRAINT (non-negotiable, per project spec):
  Answer text in the final output must be 100% raw OCR output. The LLM is
  NEVER allowed to return answer text directly — only q_start_line / q_end_line /
  a_start_line / a_end_line. All slicing happens in Python from the raw numbered
  lines. If you ever see yourself tempted to have the LLM "clean up" or "repair"
  an answer's text, that violates the constraint — don't do it.

Constants match the established project config.
"""

